import { describe, expect, it } from 'vitest';
import { cloudSessionOf, codexCloudSessions, githubCloudSessions } from './cloud.js';

const thread = 'https://claude.ai/code/project/chan_01Abc?thread=cmsg_01Def';
const pull = (number: number, body: string, extra: Record<string, unknown> = {}) => ({
  number,
  title: `Change ${number}`,
  state: 'closed',
  body,
  created_at: `2026-11-2${number}T08:00:00Z`,
  updated_at: `2026-11-2${number}T10:00:00Z`,
  repository_url: 'https://api.github.com/repos/acme/app',
  pull_request: { merged_at: `2026-11-2${number}T10:00:00Z` },
  ...extra,
});
const missing = () => Promise.reject(Object.assign(new Error('spawn gh ENOENT'), { code: 'ENOENT' }));

describe('cloudSessionOf', () => {
  it('reads the session a pull request names', () => {
    expect(
      cloudSessionOf(`_Requested by **G** · [project thread](${thread})_\nhttps://claude.ai/code/session_01X`),
    ).toEqual({
      agent: 'claude',
      id: 'cmsg_01Def',
      url: thread,
      project: 'chan_01Abc',
    });
    expect(cloudSessionOf('Made in https://claude.ai/code/session_01Xyz.')).toEqual({
      agent: 'claude',
      id: 'session_01Xyz',
      url: 'https://claude.ai/code/session_01Xyz',
    });
    expect(cloudSessionOf('[task](https://chatgpt.com/codex/tasks/task_e_68ab)')).toMatchObject({
      agent: 'codex',
      id: 'task_e_68ab',
    });
    expect(cloudSessionOf('Generated by [Claude Code](https://claude.ai/code)')).toBeUndefined();
  });
});

describe('githubCloudSessions', () => {
  const now = () => Date.parse('2026-11-24T12:00:00Z');

  it('groups pull requests by the session that opened them', async () => {
    const calls: string[][] = [];
    const source = githubCloudSessions({
      now,
      run: async (command, args) => {
        calls.push([command, ...args]);
        return JSON.stringify({
          items: [
            pull(4, `x ${thread}`, { state: 'open', pull_request: {} }),
            pull(3, 'https://claude.ai/code/session_01Solo'),
            pull(2, `y ${thread}`),
            pull(1, 'typed by hand'),
          ],
        });
      },
    });
    const sessions = await source.list({ since: Date.parse('2026-11-20T00:00:00Z') });
    expect(calls).toHaveLength(1);
    expect(calls[0]).toContain('q=is:pr author:@me updated:>=2026-11-20');
    expect(sessions).toEqual([
      {
        source: 'github',
        agent: 'claude',
        id: 'cmsg_01Def',
        where: 'cloud',
        updatedAt: Date.parse('2026-11-24T10:00:00Z'),
        startedAt: Date.parse('2026-11-22T08:00:00Z'),
        repository: 'acme/app',
        title: 'Change 4',
        url: thread,
        project: { id: 'chan_01Abc' },
        state: 'waiting',
        lastReply: 'Open: acme/app#4 Change 4; Merged: acme/app#2 Change 2',
      },
      {
        source: 'github',
        agent: 'claude',
        id: 'session_01Solo',
        where: 'cloud',
        updatedAt: Date.parse('2026-11-23T10:00:00Z'),
        startedAt: Date.parse('2026-11-23T08:00:00Z'),
        repository: 'acme/app',
        title: 'Change 3',
        url: 'https://claude.ai/code/session_01Solo',
        lastReply: 'Merged: acme/app#3 Change 3',
      },
    ]);
  });

  it('lists nothing without gh, or for a local directory, and passes other failures on', async () => {
    expect(await githubCloudSessions({ now, run: missing }).list()).toEqual([]);
    expect(await githubCloudSessions({ now, run: async () => '{"items":[]}' }).list({ cwd: '/work' })).toEqual([]);
    const refused = githubCloudSessions({ now, run: () => Promise.reject(new Error('gh: not logged in')) });
    await expect(refused.list()).rejects.toThrow('not logged in');
  });
});

describe('codexCloudSessions', () => {
  it('lists the tasks Codex gives', async () => {
    const source = codexCloudSessions({
      run: async (_command, args) => {
        expect(args).toEqual(['cloud', 'list', '--json']);
        return `WARNING: something\n${JSON.stringify({
          tasks: [
            {
              id: 'task_e_1',
              url: 'https://chatgpt.com/codex/tasks/task_e_1',
              title: 'Fix it',
              status: 'ready',
              updated_at: '2026-11-24T09:00:00Z',
              environment_label: 'acme/app',
            },
            { id: 'task_e_2', title: 'Running', status: 'pending', updated_at: '2026-11-24T10:00:00Z' },
            { id: 'task_e_0', title: 'Old', status: 'ready', updated_at: '2026-10-01T10:00:00Z' },
          ],
        })}`;
      },
    });
    const sessions = await source.list({ since: Date.parse('2026-11-01T00:00:00Z') });
    expect(sessions.map((session) => [session.id, session.state, session.repository])).toEqual([
      ['task_e_2', 'active', undefined],
      ['task_e_1', 'waiting', 'acme/app'],
    ]);
    expect(sessions[1]).toMatchObject({ agent: 'codex', where: 'cloud', source: 'codex-cloud', title: 'Fix it' });
  });

  it('lists nothing without the Codex CLI', async () => {
    expect(await codexCloudSessions({ run: missing }).list()).toEqual([]);
  });
});
